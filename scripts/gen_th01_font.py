FIRST = 0x20
LAST = 0x7E
WIDTH = 5
HEIGHT = 7  # glyph rows; written out as HRP_FONT_GLYPH_H


def encode(glyph: list[str]) -> list[int]:
    """Pack a glyph into 5 column bytes; bit N is row N (bit 0 = top)."""
    if len(glyph) != HEIGHT:
        raise ValueError(f"glyph must have {HEIGHT} rows, got {len(glyph)}")
    columns = []
    for col in range(WIDTH):
        bits = 0
        for row in range(HEIGHT):
            line = glyph[row]
            if len(line) != WIDTH:
                raise ValueError(f"row must be {WIDTH} wide: {line!r}")
            if line[col] != ".":
                bits |= 1 << row
        columns.append(bits)
    return columns


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default="highly-responsive-prayers/th01/hrp_font.h")
    args = parser.parse_args()

    missing = [chr(code) for code in range(FIRST, LAST + 1) if chr(code) not in GLYPHS]
    if missing:
        raise SystemExit(f"font is incomplete, missing: {''.join(missing)!r}")

    lines = [
        "/* hrp_font.h - 5x7 bitmap font, generated by scripts/gen_th01_font.py.",
        " *",
        " * SPDX-License-Identifier: MIT",
        " * Copyright (c) 2026 contributors to the 1warriorscats1-sys/- repository.",
        " *",
        " * Hand-designed pixel glyphs for this project. Do not edit by hand; run",
        " *   python3 scripts/gen_th01_font.py",
        " * to regenerate.",
        " */",
        "#ifndef HRP_FONT_H",
        "#define HRP_FONT_H",
        "",
        "#include <stdint.h>",
        "",
        "#define HRP_FONT_W 5",
        "#define HRP_FONT_GLYPH_H 7",
        "#define HRP_FONT_FIRST 0x20",
        "#define HRP_FONT_LAST 0x7E",
        "",
        "/* Each glyph is stored column-major: byte N holds column N, bit R is row R. */",
        "static const uint8_t hrp_font5x7[0x7F - 0x20][HRP_FONT_W] = {",
    ]

    for code in range(FIRST, LAST + 1):
        columns = encode(GLYPHS[chr(code)])
        body = ", ".join(f"0x{value:02x}" for value in columns)
        marker = f"/* {chr(code)!r} */" if chr(code) not in '"\\' else "/* special */"
        lines.append(f"    {{{body}}},  {marker}")

    lines += ["};", "", "#endif /* HRP_FONT_H */", ""]

    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out} ({LAST - FIRST + 1} glyphs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
